// Exercises the production panel, not a second implementation of its logic.
function run(panel, host, home) {
    var checks = [];
    function check(condition, name) { if (!condition) throw new Error(name); checks.push(name); }
    function key(code, repeat) { check(panel.handle(code, !!repeat), "Key handled: " + code); }
    var original = JSON.stringify(host.config), saved = host.saves;
    panel.open(false);
    panel.row = 0; panel.action = 3; key(Qt.Key_Return);
    check(panel.draft.apps[1].id === "youtube.leanback.v4", "Move app later follows focus");
    check(panel.row === 1, "Moved row stays selected");
    panel.action = 2; key(Qt.Key_Return);
    check(panel.draft.apps[0].id === "youtube.leanback.v4", "Move app earlier");
    key(Qt.Key_Return);
    check(panel.row === 0, "First row cannot move before zero");
    panel.row = 4; panel.action = 3; key(Qt.Key_Return);
    check(panel.row === 4, "Last row cannot move beyond end");
    panel.action = 4; key(Qt.Key_Return);
    check(panel.draft.apps.length === 4 && panel.row === 4, "Remove last app selects Add row");
    key(Qt.Key_Return);
    check(panel.view === "picker", "Add row opens app picker");
    var netflix = -1;
    for (var i = 0; i < panel.choices.length; ++i) if (panel.choices[i].id === "netflix") netflix = i;
    check(netflix >= 0, "Discovered installed apps offered");
    panel.pickerRow = netflix; key(Qt.Key_Return);
    check(panel.draft.apps[4].id === "netflix" && !panel.draft.apps[4].icon, "Add installed app; device icon path not persisted");
    check(panel.listCount === 5 && !panel.canAdd, "Five-app limit hides Add");
    key(Qt.Key_Escape);
    check(!panel.opened && JSON.stringify(host.config) === original, "Back discards complete draft");
    panel.open(false); panel.selectSection("inputs");
    panel.row = 2; panel.action = 0; key(Qt.Key_Return);
    check(panel.view === "rename", "OK on tile starts rename");
    panel.renameValue = "Apple TV"; panel.keyboardIndex = 44; key(Qt.Key_Return);
    check(panel.draft.inputs[2].label === "Apple TV" && panel.draft.inputs[2].port === 3, "Rename retains physical HDMI port");
    panel.action = 2; key(Qt.Key_Return);
    check(panel.draft.inputs[1].port === 3, "HDMI order independent from physical number");
    panel.action = 0; key(Qt.Key_Return); panel.renameValue = "Changed"; key(Qt.Key_Escape);
    check(panel.draft.inputs[1].label === "Apple TV" && panel.opened, "Back cancels nested rename only");
    key(Qt.Key_Return); panel.renameValue = "   "; panel.keyboardIndex = 44; key(Qt.Key_Return);
    check(panel.view === "rename" && panel.errorText.length > 0, "Empty name rejected without leaving editor");
    panel.typeKey(38); panel.lowerCase = false; panel.typeKey(0); panel.typeKey(39); panel.typeKey(1); panel.typeKey(36); panel.typeKey(26);
    check(panel.renameValue === "Ab 0", "Remote keyboard supports mixed case, spaces and digits");
    panel.typeKey(37); check(panel.renameValue === "Ab ", "Remote keyboard delete removes one character");
    panel.renameValue = new Array(41).join("x"); panel.typeKey(0);
    check(panel.renameValue.length === 40, "Remote keyboard caps names at 40 characters");
    panel.keyboardIndex = 0; key(Qt.Key_Left); check(panel.keyboardIndex === 44, "Remote keyboard wraps safely");
    key(Qt.Key_Escape); panel.action = 1; key(Qt.Key_Return);
    check(panel.choices.length === 1 && panel.choices[0].port === 3, "Changing HDMI cannot duplicate an in-use port");
    key(Qt.Key_Escape);
    panel.zone = 2; panel.footer = 1; key(Qt.Key_Return, true);
    check(host.saves === saved, "Held OK does not repeat Save");
    host.failSave = true; key(Qt.Key_Return);
    check(panel.opened && panel.errorText.indexOf("Mock storage") >= 0 && JSON.stringify(host.config) === original, "Failed save keeps draft and existing config");
    host.failSave = false; key(Qt.Key_Return);
    check(!panel.opened && host.saves === saved + 1 && host.config.inputs[1].label === "Apple TV", "Successful save closes and commits complete draft");
    panel.open(false);
    while (panel.draft.apps.length) { panel.row = 0; panel.removeEntry(); }
    panel.selectSection("inputs");
    while (panel.draft.inputs.length) { panel.row = 0; panel.removeEntry(); }
    panel.save();
    check(panel.opened && panel.errorText.indexOf("At least one") >= 0, "Cannot save an empty launcher");
    panel.beginPicker(true); panel.choose(0);
    check(panel.draft.inputs.length === 1 && panel.draft.inputs[0].port === 1, "Inputs-only configuration supported");
    panel.save(); check(!panel.opened, "Single-input config saves");
    panel.open(false); panel.selectSection("apps"); home.inventoryAvailable = false; home.installedApps = [];
    panel.beginPicker(true);
    check(panel.choices.length === 0, "Unavailable discovery handled with empty choices");
    key(Qt.Key_Down); key(Qt.Key_Return); key(Qt.Key_Escape);
    check(panel.view === "list" && panel.opened, "Empty picker accepts Back and remains responsive");
    panel.close(); host.config = JSON.parse(original); host.saves = saved;
    home.installedApps = host.appInventory; home.inventoryAvailable = true;
    panel.open(false); key(Qt.Key_Up);
    check(panel.zone === 0, "Up from first row reaches tabs");
    key(Qt.Key_Right); check(panel.section === "inputs", "Left/right changes category");
    key(Qt.Key_Down); check(panel.zone === 1 && panel.row === 0, "Down returns to first row");
    for (i = 0; i < 4; ++i) key(Qt.Key_Down);
    check(panel.zone === 2 && panel.footer === 1, "Down through final row reaches Save");
    key(Qt.Key_Left); key(Qt.Key_Return);
    check(!panel.opened && host.saves === saved, "Explicit Cancel does not save");
    panel.close();
    var single = JSON.parse(original); single.apps = [{id: "netflix", label: "Netflix"}]; single.inputs = [];
    host.config = single; home.select(0);
    check(home.targetCount === 1, "Production HomeControls one-app model");
    home.handleKey(Qt.Key_Right, false); check(home.selectedIndex === 0, "Right stops at final tile");
    home.handleKey(Qt.Key_Left, false); check(home.selectedIndex === 0, "Left stops at first tile");
    home.handleKey(Qt.Key_Return, false); check(host.lastLaunch === "netflix", "Production launch uses configured app ID");
    home.handleKey(Qt.Key_Down, false); check(home.selectedIndex === home.appearanceIndex, "Down selects Appearance");
    home.handleKey(Qt.Key_Left, false); check(home.selectedIndex === home.setupIndex, "Footer left selects Apps & Inputs");
    home.handleKey(Qt.Key_Left, false); check(home.selectedIndex === home.lgHomeIndex, "Footer left selects LG Home");
    var stockCount = host.stockHomeCount;
    home.handleKey(Qt.Key_Return, false); check(host.stockHomeCount === stockCount + 1, "LG Home footer emits stock Home request");
    home.handleKey(Qt.Key_Red, true); check(host.stockHomeCount === stockCount + 1, "Held Red does not repeat stock Home request");
    home.handleKey(Qt.Key_Red, false); check(host.stockHomeCount === stockCount + 2, "Red emits stock Home request");
    home.handleKey(Qt.Key_Up, false); check(home.selectedIndex === 0, "Up restores last app tile");
    home.handleKey(Qt.Key_Back, false); check(!panel.opened, "Back on home leaves launcher in place");
    single = JSON.parse(original); single.apps = []; single.inputs = [{port: 4, label: "Switch"}]; host.config = single;
    home.select(0); home.handleKey(Qt.Key_Return, false);
    check(home.targetCount === 1 && host.lastLaunch === "com.webos.app.hdmi4", "Production inputs-only layout launches physical port");
    single.inputs = [{port: 4, label: "Switch"}, {port: 2, label: "Console"}]; host.config = JSON.parse(JSON.stringify(single));
    home.select(1); home.handleKey(Qt.Key_Return, false); check(host.lastLaunch === "com.webos.app.hdmi2", "Reordered HDMI targets remain correct");
    home.openSetup(false); home.handleKey(Qt.Key_Back, false);
    check(!panel.opened && home.selectedIndex === home.setupIndex, "Back closes setup and restores footer focus");
    home.openSetup(false); home.handleKey(461, false);
    check(!panel.opened, "Browser Back code also dismisses setup");
    home.nativeBackKey = 16777313; home.openSetup(false); home.handleKey(16777313, false);
    check(!panel.opened, "Platform Back alias dismisses setup");
    home.nativeBackKey = -1;
    home.select(home.appearanceIndex); home.handleKey(Qt.Key_Return, false); home.handleKey(Qt.Key_Back, false);
    check(home.selectedIndex === home.appearanceIndex, "Back from Appearance restores its footer focus");
    home.inventoryAvailable = false; home.installedApps = []; home.openSetup(false);
    check(!panel.inventoryAvailable && panel.installedApps.length === 0, "Production discovery-denied binding reaches editor");
    check(!panel.appUnavailable({id: "org.missing"}), "Unavailable discovery does not label every app missing");
    home.inventoryAvailable = true;
    check(panel.appUnavailable({id: "org.missing"}), "Successful inventory flags absent app shortcuts");
    home.handleKey(Qt.Key_Back, false);
    for (i = 0; i < 10; ++i) { home.openSetup(false); home.handleKey(Qt.Key_Back, false); }
    check(!panel.opened, "Repeated setup opens and Back retain stable focus");
    var literal = JSON.parse(original); literal.apps[0].label = "<b>literal</b>";
    host.config = literal; home.installedApps = host.appInventory; home.inventoryAvailable = true; panel.open(false);
    var labelItem = host.findItem(panel, "shortcutLabel0_0");
    check(labelItem && labelItem.text === "<b>literal</b>" && labelItem.textFormat === host.plainTextFormat, "HTML-looking app label displays literally, never as markup");
    var lots = [];
    for (i = 0; i < 50; i++) lots.push({id: "org.preview.app" + i, label: "Installed app " + i});
    home.installedApps = lots; panel.beginPicker(false);
    check(panel.choices.length === 50, "Long installed-app inventory contains all 50 choices");
    var picker = host.findItem(panel, "appPickerList"); picker.forceLayout();
    for (i = 0; i < 49; i++) panel.handle(Qt.Key_Down, false);
    picker.forceLayout();
    check(panel.pickerRow === 49 && picker.currentIndex === 49, "Remote navigation reaches last installed app");
    check(picker.contentY > 0 && picker.currentItem && picker.currentItem.y >= picker.contentY && picker.currentItem.y + picker.currentItem.height <= picker.contentY + picker.height + 1, "Long inventory scrolls last focused choice into visible viewport");
    panel.handle(Qt.Key_Return, false);
    check(panel.draft.apps[0].id === "org.preview.app49", "Last app in scrolled inventory can be selected");
    panel.close();
    host.config = JSON.parse(original); home.installedApps = host.appInventory; home.inventoryAvailable = true; home.select(0);
    panel.open(true);
    return {passed: true, assertions: checks.length, checks: checks, scope: "Production QML panel in desktop mock; not TV validation"};
}
